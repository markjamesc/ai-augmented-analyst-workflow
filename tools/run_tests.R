a<-commandArgs(TRUE);repo<-normalizePath(if(length(a))a[1] else '.',winslash='/')
out<-if(length(a)>1)a[2] else tempfile('acc003-tests-')
if(file.exists(out))stop('Use a new evidence directory');dir.create(out,recursive=TRUE)
out<-normalizePath(out,winslash='/')
r<-file.path(R.home('bin'),if(.Platform$OS.type=='windows')'Rscript.exe' else 'Rscript')
suites<-c('workflow-gate/tests/test_workflow_gate.R','procedure-gate/tests/test_procedure_gate.R','methodology/tests/test_schema.R','methodology/tests/test_methodology.R','methodology/tests/test_acceptance.R')
Sys.setenv(WF_TEST_EVIDENCE=out)
results<-list()
for(s in suites){log<-file.path(out,paste0(basename(s),'.log'));code<-system2(r,c('--vanilla',shQuote(file.path(repo,s)),shQuote(repo)),stdout=log,stderr=log);results[[s]]<-list(exit=as.integer(code),log=basename(log));cat(s,if(code==0)'PASS' else 'FAILED','\n')}
jsonlite::write_json(list(r=R.version.string,results=results),file.path(out,'RESULTS.json'),auto_unbox=TRUE,pretty=TRUE)
writeLines(capture.output(sessionInfo()),file.path(out,'R-session.txt'))
if(any(vapply(results,function(x)x$exit!=0,logical(1))))quit(status=1L)
cat('ALL_FIVE_SUITES_PASS\n')
